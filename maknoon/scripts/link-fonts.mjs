#!/usr/bin/env node
// Scans assets/fonts/thmanyah for the Thmanyah font files you downloaded from the
// official site (font.thmanyah.com — the only source the licence allows) and writes
// src/theme/thmanyah.local.native.ts so the iOS/Android app bundles them.
// The web build never loads them (licence: files must not be extractable by end users).
// The font files are git-ignored: the licence forbids hosting or sharing them.
import { readdirSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'assets/fonts/thmanyah');
const out = join(root, 'src/theme/thmanyah.local.native.ts');

// family keyword in file name → registered family prefix
const families = [
  [/serif[-_ ]?display/i, 'ThmanyahSerifDisplay'],
  [/serif[-_ ]?text/i, 'ThmanyahSerifText'],
  [/sans/i, 'ThmanyahSans'],
];
const weights = ['Black', 'Bold', 'Medium', 'Regular', 'Light'];

const files = readdirSync(dir).filter((f) => /\.(otf|ttf)$/i.test(f));
const entries = [];
for (const f of files) {
  const fam = families.find(([re]) => re.test(f));
  const w = weights.find((x) => new RegExp(x, 'i').test(f));
  if (!fam || !w) continue;
  entries.push(`  '${fam[1]}-${w}': require('../../assets/fonts/thmanyah/${f}'),`);
}

writeFileSync(
  out,
  `// Generated by \`npm run fonts:link\` (iOS/Android only). Font files stay git-ignored (Thmanyah licence).\n` +
    `export const thmanyahFonts: Record<string, number> = {\n${entries.join('\n')}\n};\n`,
);
console.log(`Linked ${entries.length} Thmanyah font file(s).`);
if (!entries.length) console.log('No .otf/.ttf files found in assets/fonts/thmanyah — fallbacks stay active.');

// Keep the generated (local) font map out of commits: the committed copy stays empty
// so clones without the font files still build.
try {
  execFileSync('git', ['update-index', '--skip-worktree', 'src/theme/thmanyah.local.native.ts'], { cwd: root, stdio: 'ignore' });
} catch {
  // not a git checkout — nothing to do
}
